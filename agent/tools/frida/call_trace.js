Process.enumerateModulesSync()
    .forEach(function(m) {
        if (modulesToHook[m.name]) {
            Module.ensureInitialized(m.name);
            Module.enumerateExports(m.name, {
                onMatch: function (exp) {
                    try {    
                        if (exp.type == 'function' && modulesToHook[m.name.toUpperCase()].includes(exp.name)) {
                            Interceptor.attach(Module.findExportByName(m.name, exp.name), {
                                onEnter: function (args) {
                                    send(`{ "module": "${m.name}", "function": "${exp.name}", "address": "${exp.address}" }`);
                                },
                                onLeave: function (retval) {
                                    // Código de saída da função
                                }
                            });
                        }
                    } catch (error) {
                        console.error(error)
                    }
                },
                onComplete: function() {}
            });
        }
    });
